"""Constants package for the NeuralBridge integration.

This package replaces the monolithic ``const.py`` file.  Each module
covers one logical domain:

* :mod:`.core`        — domain identity, language, storage, agent types,
                        priority ranges, hass.data keys, services, messages
* :mod:`.agent`       — per-agent config (prompts, assist mode, complexity,
                        retry, circuit breaker, cache, sentinel token)
* :mod:`.guard_rail`  — guard rail configuration, actions, messages, events
* :mod:`.router`      — router classification prompt, response keys,
                        fallback/failover modes, log levels, strategies
* :mod:`.web_search`  — web search providers and configuration
* :mod:`.benchmark`   — agent benchmark / profiling (Feature 14)
* :mod:`.preference`  — adaptive preference learning (Feature 15)
* :mod:`.features`    — broadcast, high-stakes, response cache, verbosity,
                        language passthrough, compound commands, home control

**Adding new constants:**
  Do NOT add constants directly to this file.  Instead:
  1. Identify the correct domain module (or create a new one for a new domain).
  2. Add the constant to that module.
  3. Add the name to the ``__all__`` list in that module (if you add one) or
     simply rely on the wildcard re-export below.

All existing ``from .const import X`` call-sites continue to work unchanged
because Python resolves ``neuralbridge.const`` to this package.
"""

